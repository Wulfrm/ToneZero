import {readFile,writeFile} from 'node:fs/promises';
const core=await readFile(new URL('../dist/core.js',import.meta.url),'utf8');
const worker=await readFile(new URL('../worker/index.js',import.meta.url),'utf8');
// Both inputs are plain JavaScript modules owned by this project. No dependencies.
const bundle='// Generated by scripts/bundle-worker.mjs. Edit core.js / worker/index.js instead.\n'+core.replace(/^export /gm,'')+'\n'+worker.replace(/^import[^\n]+\n/,'').replace('export function makeHandler','function makeHandler');
await writeFile(new URL('../worker/deploy.js',import.meta.url),bundle);
console.log('Prepared worker/deploy.js for the Cloudflare dashboard editor.');
